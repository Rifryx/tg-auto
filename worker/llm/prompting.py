"""Единые правила вывода для всех обращений к LLM в сервисе.

Проблема, которую это решает: без жёсткой инструкции модель отвечает как
ассистент — «вот несколько вариантов комментария для поста #57: 1. …» вместо
одного готового текста. Эта добавка в system prompt заставляет LLM выдавать
СРАЗУ финальную реплику, которую можно публиковать как есть.
"""

from __future__ import annotations

# Для «текстовых» вызовов (коммент, живой ответ): нужен один готовый текст.
DIRECT_OUTPUT_RULE = (
    "ФОРМАТ ОТВЕТА (строго): выведи СРАЗУ готовый текст — одну финальную реплику "
    "и больше ничего. Запрещено: предлагать несколько вариантов, нумеровать, "
    "писать вступления и мета-фразы вроде «вот несколько вариантов», «как "
    "ассистент», «я бы написал так», «варианты ответа». Без кавычек вокруг, без "
    "пояснений до или после, без подписи. Пиши от первого лица на языке поста "
    "или собеседника, как обычный живой участник чата."
)


def with_direct_output(system_prompt: str) -> str:
    """Добавляет правило «выводи сразу готовый текст» к любому system-промпту."""
    base = (system_prompt or "").rstrip()
    return f"{base}\n\n{DIRECT_OUTPUT_RULE}"
