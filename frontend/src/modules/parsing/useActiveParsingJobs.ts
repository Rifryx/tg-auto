import { useQuery } from "@tanstack/react-query";
import { parsingApi } from "./api";

/* Есть ли сейчас выполняющаяся/ожидающая/на паузе задача парсинга — для
   индикатора в навигации («идёт парсинг»). Опрашивается глобально (со всех
   экранов, не только с «Парсинга») — жалоба: «я хочу чтобы отображалась
   зацикленная анимация ... там где пользователь выбирает сервис», плюс
   неявный вопрос «не прекратится ли парсинг, если я уйду с экрана» — сам
   job выполняется на воркере независимо от открытого экрана (arq-задача,
   см. modules/parsing/worker/dispatch.py), поэтому индикатор в навигации —
   честный ответ: раз он горит с любого экрана, значит парсинг идёт фоном.

   Лёгкий /jobs/active (COUNT, без логов) — не /jobs (полные записи с логом
   до 500 строк каждая), который было бы тяжело дёргать каждые несколько
   секунд с КАЖДОГО экрана приложения. */
export function useActiveParsingJobs() {
  const query = useQuery({
    queryKey: ["parsing", "jobs", "active"],
    queryFn: () => parsingApi.activeJobs(),
    refetchInterval: 8_000,
    staleTime: 4_000,
  });
  return query.data?.active ?? false;
}
